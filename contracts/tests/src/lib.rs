    fn build_signed_witness(
        privkey_hex: &str,
        pair: &str,
        price_scaled: u64,
        block_number: u64,
        tip_block_hash: [u8; 32],
    ) -> ([u8; 32], Vec<u8>) {
        let sk_bytes = hex::decode(privkey_hex).unwrap();
        let signing_key = SigningKey::from_bytes(&sk_bytes).unwrap();
        let pubkey_bytes: [u8; 32] = signing_key.verifying_key().to_bytes().into();

        let mut payload = [0u8; PAYLOAD_SIZE];
        payload[0..4].copy_from_slice(&ORACELL_MAGIC);
        payload[4] = ORACELL_VERSION;
        let pair_bytes = pair.as_bytes();
        payload[5..5 + pair_bytes.len()].copy_from_slice(pair_bytes);
        payload[21..29].copy_from_slice(&price_scaled.to_le_bytes());
        payload[29] = 8; // decimals
        payload[30..38].copy_from_slice(&1794966400000u64.to_le_bytes());
        payload[38..46].copy_from_slice(&block_number.to_le_bytes());
        payload[46..78].copy_from_slice(&tip_block_hash);
        payload[78..86].copy_from_slice(&1794966398000u64.to_le_bytes());
        payload[86] = 2; // source_count
        payload[87] = 0; // flags

        let digest = Sha256::digest(payload);
        let sig = signing_key.sign_raw(&digest, &[0u8; 32]).unwrap();
        let sig_bytes: [u8; 64] = sig.to_bytes();

        let mut witness = Vec::with_capacity(WITNESS_SIZE);
        witness.extend_from_slice(&payload);
        witness.extend_from_slice(&pubkey_bytes);
        witness.extend_from_slice(&sig_bytes);

        (pubkey_bytes, witness)
    }

    fn load_verifier_binary() -> Bytes {
        let manifest_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
        let bin_path = manifest_dir
            .parent()
            .unwrap()
            .join("target/riscv64imac-unknown-none-elf/release/oracell-verifier");
        assert!(
            bin_path.exists(),
            "RISC-V binary not found at {:?}. Run `cargo build --release -p oracell-verifier --target riscv64imac-unknown-none-elf` first.",
            bin_path
        );
        fs::read(bin_path).unwrap().into()
    }

    #[test]
    fn test_cross_language_ts_schnorr_witness_verifies_in_rust() {
        let pubkey_vec = hex::decode(TS_PUBKEY_HEX).unwrap();
        let witness_vec = hex::decode(TS_WITNESS_HEX).unwrap();
        let tip_hash: [u8; 32] =
            hex::decode("2744652538156731685b79f596bc828099ca7280fc50de9f5db4b8c47da80118")
                .unwrap()
                .try_into()
                .unwrap();

        let header_deps = [HeaderDepInfo {
            hash: tip_hash,
            number: 23099353,
        }];

        let parsed = verify_oracle_proof(&pubkey_vec, &[&witness_vec], &header_deps)
            .expect("TS-signed witness should verify identically in Rust");
        assert_eq!(parsed.price_scaled, 89900);
        assert_eq!(parsed.block_number, 23099353);
    }

    #[test]
    fn test_core_rejects_tampered_payload_wrong_pubkey_and_stale_block() {
        let tip_hash = [0x42u8; 32];
        let (pubkey, mut witness) =
            build_signed_witness(TEST_PRIVKEY_HEX, "BTC/USDT", 6443640000000, 100, tip_hash);

        // Fresh window (lag = 2 <= 2) passes
        let headers_fresh = [
            HeaderDepInfo {
                hash: tip_hash,
                number: 100,
            },
            HeaderDepInfo {
                hash: [0x99u8; 32],
                number: 102,
            },
        ];
        assert!(verify_oracle_proof(&pubkey, &[&witness], &headers_fresh).is_ok());

        // Stale window (lag = 3 > 2) fails with StaleOracleBlock
        let headers_stale = [
            HeaderDepInfo {
                hash: tip_hash,
                number: 100,
            },
            HeaderDepInfo {
                hash: [0x99u8; 32],
                number: 103,
            },
        ];
        assert_eq!(
            verify_oracle_proof(&pubkey, &[&witness], &headers_stale),
            Err(VerifierError::StaleOracleBlock)
        );

        // Configurable window (max_lag = 5 in args[32..40]) allows lag = 3
        let mut args_lag_5 = Vec::with_capacity(40);
        args_lag_5.extend_from_slice(&pubkey);
        args_lag_5.extend_from_slice(&5u64.to_le_bytes());
        assert!(verify_oracle_proof(&args_lag_5, &[&witness], &headers_stale).is_ok());

        // Missing tip_block_hash in header_deps fails with TipHeaderNotInDeps
        let headers_missing = [HeaderDepInfo {
            hash: [0x99u8; 32],
            number: 100,
        }];
        assert_eq!(
            verify_oracle_proof(&pubkey, &[&witness], &headers_missing),
            Err(VerifierError::TipHeaderNotInDeps)
        );

        // Wrong pubkey fails with PubkeyMismatch
        let wrong_pubkey = [0x11u8; 32];
        assert_eq!(
            verify_oracle_proof(&wrong_pubkey, &[&witness], &headers_fresh),
            Err(VerifierError::PubkeyMismatch)
        );

        // Tampered price fails Schnorr signature verification
        witness[21] ^= 0xff;
        assert_eq!(
            verify_oracle_proof(&pubkey, &[&witness], &headers_fresh),
            Err(VerifierError::InvalidSignature)
        );
    }

    fn make_header(number: u64, parent_seed: u8) -> HeaderView {
        HeaderBuilder::default()
            .number(number.pack())
            .epoch(EpochNumberWithFraction::new(1, 0, 1000).full_value().pack())
            .parent_hash([parent_seed; 32].pack())
            .build()
    }

    #[test]
    fn test_ckb_vm_riscv_stateless_witness_verification_and_header_deps() {
        let mut context = Context::default();
        let contract_bin = load_verifier_binary();
        let verifier_out_point = context.deploy_cell(contract_bin);
        let always_success_out_point = context.deploy_cell(ALWAYS_SUCCESS.clone());

        let header_100 = make_header(100, 1);
        let header_102 = make_header(102, 2);
        let header_103 = make_header(103, 3);
        context.insert_header(header_100.clone());
        context.insert_header(header_102.clone());
        context.insert_header(header_103.clone());

        let tip_hash: [u8; 32] = header_100.hash().as_slice().try_into().unwrap();
        let (pubkey, oracle_witness) =
            build_signed_witness(TEST_PRIVKEY_HEX, "CKB/USDT", 89900, 100, tip_hash);

        let lock_script = context
            .build_script(&always_success_out_point, Bytes::from(vec![0u8]))
            .unwrap();
        let oracell_type_script = context
            .build_script(&verifier_out_point, Bytes::copy_from_slice(&pubkey))
            .unwrap();

        // 1) Valid transaction with raw Oracell witness + header_deps (lag = 2 <= 2)
        let input_out_point = context.create_cell(
            CellOutput::new_builder()
                .capacity(1000_0000_0000u64.pack())
                .lock(lock_script.clone())
                .build(),
            Bytes::new(),
        );
        let tx_valid = TransactionBuilder::default()
            .input(
                CellInput::new_builder()
                    .previous_output(input_out_point)
                    .build(),
            )
            .output(
                CellOutput::new_builder()
                    .capacity(999_0000_0000u64.pack())
                    .lock(lock_script.clone())
                    .type_(Some(oracell_type_script.clone()).pack())
                    .build(),
            )
            .output_data(Bytes::new().pack())
            .header_dep(header_100.hash())
            .header_dep(header_102.hash())
            .witness(Bytes::new().pack())
            .witness(Bytes::from(oracle_witness.clone()).pack())
            .build();
        let tx_valid = context.complete_tx(tx_valid);
        let cycles = context
            .verify_tx(&tx_valid, MAX_CYCLES)
            .expect("CKB-VM should accept valid Oracell witness and fresh header_dep");
        assert!(cycles > 0 && cycles < MAX_CYCLES);

        // 2) Valid transaction with Oracell witness wrapped inside Molecule WitnessArgs.output_type
        let witness_args = WitnessArgs::new_builder()
            .output_type(Some(Bytes::from(oracle_witness.clone())).pack())
            .build();
        let input_out_point_2 = context.create_cell(
            CellOutput::new_builder()
                .capacity(1000_0000_0000u64.pack())
                .lock(lock_script.clone())
                .build(),
            Bytes::new(),
        );
        let tx_witness_args = TransactionBuilder::default()
            .input(
                CellInput::new_builder()
                    .previous_output(input_out_point_2)
                    .build(),
            )
            .output(
                CellOutput::new_builder()
                    .capacity(999_0000_0000u64.pack())
                    .lock(lock_script.clone())
                    .type_(Some(oracell_type_script.clone()).pack())
                    .build(),
            )
            .output_data(Bytes::new().pack())
            .header_dep(header_100.hash())
            .witness(witness_args.as_bytes().pack())
            .build();
        let tx_witness_args = context.complete_tx(tx_witness_args);
        context
            .verify_tx(&tx_witness_args, MAX_CYCLES)
            .expect("CKB-VM should accept WitnessArgs-wrapped Oracell proof");

        // 3) Stale block window (header_103 -> lag 3 > 2) must fail inside CKB-VM!
        let input_out_point_3 = context.create_cell(
            CellOutput::new_builder()
                .capacity(1000_0000_0000u64.pack())
                .lock(lock_script.clone())
                .build(),
            Bytes::new(),
        );
        let tx_stale = TransactionBuilder::default()
            .input(
                CellInput::new_builder()
                    .previous_output(input_out_point_3)
                    .build(),
            )
            .output(
                CellOutput::new_builder()
                    .capacity(999_0000_0000u64.pack())
                    .lock(lock_script.clone())
                    .type_(Some(oracell_type_script.clone()).pack())
                    .build(),
            )
            .output_data(Bytes::new().pack())
            .header_dep(header_100.hash())
            .header_dep(header_103.hash())
            .witness(Bytes::from(oracle_witness.clone()).pack())
            .build();
        let tx_stale = context.complete_tx(tx_stale);
        assert!(
            context.verify_tx(&tx_stale, MAX_CYCLES).is_err(),
            "CKB-VM must reject stale oracle block (lag > 2)"
        );

        // 4) Missing tip_block_hash in header_deps must fail inside CKB-VM!
        let input_out_point_4 = context.create_cell(
            CellOutput::new_builder()
                .capacity(1000_0000_0000u64.pack())
                .lock(lock_script.clone())
                .build(),
            Bytes::new(),
        );
        let tx_missing_hdr = TransactionBuilder::default()
            .input(
                CellInput::new_builder()
                    .previous_output(input_out_point_4)
                    .build(),
            )
            .output(
                CellOutput::new_builder()
                    .capacity(999_0000_0000u64.pack())
                    .lock(lock_script.clone())
                    .type_(Some(oracell_type_script.clone()).pack())
                    .build(),
            )
            .output_data(Bytes::new().pack())
            .header_dep(header_102.hash())
            .witness(Bytes::from(oracle_witness).pack())
            .build();
        let tx_missing_hdr = context.complete_tx(tx_missing_hdr);
        assert!(
            context.verify_tx(&tx_missing_hdr, MAX_CYCLES).is_err(),
            "CKB-VM must reject tx missing payload.tip_block_hash in header_deps"
        );
    }
    #[test]
    fn measure_contention_scenarios() {
        use std::collections::HashSet;

        let mut context = Context::default();
        let verifier = context.deploy_cell(load_verifier_binary());
        let baseline = context.deploy_cell(ALWAYS_SUCCESS.clone());
        let lock = context.build_script(&baseline, Bytes::new()).unwrap();
        let header = make_header(200, 1);
        context.insert_header(header.clone());
        let (key, proof) = build_signed_witness(
            TEST_PRIVKEY_HEX,
            "CKB/USDT",
            89900,
            200,
            header.hash().as_slice().try_into().unwrap(),
        );
        let verifier_script = context
            .build_script(&verifier, Bytes::copy_from_slice(&key))
            .unwrap();
        let make_cell = || {
            CellOutput::new_builder()
                .capacity(1000_0000_0000u64.pack())
                .lock(lock.clone())
                .build()
        };
        let shared = context.create_cell(make_cell(), Bytes::new());
        let mut spent = HashSet::new();
        let mut baseline_verified = 0;
        let mut baseline_cycles = 0;
        for _ in 0..20 {
            let own = context.create_cell(make_cell(), Bytes::new());
            let tx = TransactionBuilder::default()
                .input(CellInput::new_builder().previous_output(own).build())
                .input(
                    CellInput::new_builder()
                        .previous_output(shared.clone())
                        .build(),
                )
                .output(make_cell())
                .output_data(Bytes::new().pack())
                .build();
            // The emulator verifies scripts. This ordered admission model applies
            // the UTXO rule that a consumed outpoint cannot be admitted twice.
            if tx
                .inputs()
                .into_iter()
                .any(|input| spent.contains(&input.previous_output()))
            {
                continue;
            }
            let tx = context.complete_tx(tx);
            let cycles = context.verify_tx(&tx, MAX_CYCLES).unwrap();
            spent.extend(tx.inputs().into_iter().map(|input| input.previous_output()));
            baseline_verified += 1;
            baseline_cycles += cycles;
        }

        let mut witness_cycles = Vec::new();
        for _ in 0..100 {
            let own = context.create_cell(make_cell(), Bytes::new());
            assert!(spent.insert(own.clone()));
            let tx = TransactionBuilder::default()
                .input(CellInput::new_builder().previous_output(own).build())
                .output(
                    make_cell()
                        .as_builder()
                        .type_(Some(verifier_script.clone()).pack())
                        .build(),
                )
                .output_data(Bytes::new().pack())
                .header_dep(header.hash())
                .witness(Bytes::new().pack())
                .witness(Bytes::copy_from_slice(&proof).pack())
                .build();
            let tx = context.complete_tx(tx);
            witness_cycles.push(context.verify_tx(&tx, MAX_CYCLES).unwrap());
        }
        assert_eq!(baseline_verified, 1);
        assert_eq!(witness_cycles.len(), 100);
        println!(
            "ORACELL_BENCHMARK {{\"baseline\":{{\"submitted\":20,\"verified\":{},\"conflicts\":{},\"cycles\":{}}},\"oracell\":{{\"submitted\":100,\"verified\":{},\"conflicts\":0,\"minCycles\":{},\"maxCycles\":{},\"totalCycles\":{}}}}}",
            baseline_verified, 20 - baseline_verified, baseline_cycles, witness_cycles.len(),
            witness_cycles.iter().min().unwrap(), witness_cycles.iter().max().unwrap(),
            witness_cycles.iter().sum::<u64>(),
        );
    }
